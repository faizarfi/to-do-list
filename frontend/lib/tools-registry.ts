export const TOOL_BY_ID: Record<string, ToolDefinition> = Object.fromEntries(
  ALL_TOOLS.map((tool) => [tool.id, tool])
);

export function getCategoryMeta(categoryId: ToolCategoryId): ToolCategoryMeta {
  const found = TOOL_CATEGORIES.find((category) => category.id === categoryId);
  if (!found) {
    throw new Error(`Unknown category: ${categoryId}`);
  }
  return found;
}

export function getToolsByCategory(categoryId: ToolCategoryId): ToolDefinition[] {
  return ALL_TOOLS.filter((tool) => tool.category === categoryId);
}

export function searchTools(query: string, category?: ToolCategoryId): ToolDefinition[] {
  const normalized = query.trim().toLowerCase();
  const base = category ? getToolsByCategory(category) : ALL_TOOLS;
  if (!normalized) return base;

  const tokens = normalized.split(/\s+/).filter(Boolean);
  return base.filter((tool) => {
    const haystack = [
      tool.name,
      tool.shortDescription,
      tool.slug,
      String(tool.number),
      tool.category,
      ...tool.keywords,
    ]
      .join(" ")
      .toLowerCase();

    return tokens.every((token) => haystack.includes(token));
  });
}

